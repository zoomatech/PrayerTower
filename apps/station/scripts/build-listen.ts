// Bundles the burst decoder (src/burst/web.ts) for the server's /listen page,
// and as a module for the app's Listen screen. Run after changing the decoder:
// npm run build:listen -w @prayer-tower/station (a station test fails while
// either committed bundle is out of date).
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const here = path.dirname(fileURLToPath(import.meta.url));
export const OUTPUT = path.resolve(here, '../../server/src/modules/listen/decoder.generated.ts');
export const APP_OUTPUT = path.resolve(here, '../../mobile/src/lib/burst-decoder.generated.js');

const compile = async (format: 'iife' | 'esm') =>
  (
    await build({
      entryPoints: [path.resolve(here, '../src/burst/web.ts')],
      bundle: true,
      platform: 'browser',
      format,
      ...(format === 'iife' ? { globalName: 'PTDecoder' } : {}),
      minify: true,
      target: 'es2020',
      write: false,
      legalComments: 'none',
    })
  ).outputFiles[0]!.text.trim();

/** The app's copy: an ES module (types in burst-decoder.generated.d.ts). */
export async function appBundle(): Promise<string> {
  return `/* eslint-disable */\n// Generated by apps/station/scripts/build-listen.ts from apps/station/src/burst/web.ts. Do not edit.\n${await compile('esm')}\n`;
}

export async function bundle(): Promise<string> {
  const js = (await compile('iife')).replaceAll('</script', '<\\/script');
  return `// Generated by apps/station/scripts/build-listen.ts from apps/station/src/burst/web.ts. Do not edit.\nexport const DECODER_JS = ${JSON.stringify(js)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUTPUT, await bundle());
  writeFileSync(APP_OUTPUT, await appBundle());
  console.log(`wrote ${OUTPUT} and ${APP_OUTPUT}`);
}
