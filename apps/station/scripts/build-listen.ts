// Bundles the burst decoder (src/burst/web.ts) for the server's /listen page.
// Run after changing the decoder: npm run build:listen -w @prayer-tower/station
// (a station test fails while the committed bundle is out of date).
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const here = path.dirname(fileURLToPath(import.meta.url));
export const OUTPUT = path.resolve(here, '../../server/src/modules/listen/decoder.generated.ts');

export async function bundle(): Promise<string> {
  const result = await build({
    entryPoints: [path.resolve(here, '../src/burst/web.ts')],
    bundle: true,
    platform: 'browser',
    format: 'iife',
    globalName: 'PTDecoder',
    minify: true,
    target: 'es2020',
    write: false,
    legalComments: 'none',
  });
  const js = result.outputFiles[0]!.text.trim().replaceAll('</script', '<\\/script');
  return `// Generated by apps/station/scripts/build-listen.ts from apps/station/src/burst/web.ts. Do not edit.\nexport const DECODER_JS = ${JSON.stringify(js)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUTPUT, await bundle());
  console.log(`wrote ${OUTPUT}`);
}
